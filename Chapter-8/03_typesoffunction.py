# Types of Functions in Python

# Functions in Python can be broadly categorized into **two main types**:

# 1. Built-in Functions
# 2. User-defined Functions
# 3. Specialized Functions

# 1. Built-in Functions:
# Instead of writing a function to calculate length of a string:
s = "Python"
print(len(s))  # Output: 6

# 2. User-defined Functions
# Syntax:
# def function_name(parameters):
#     """
#     Optional docstring: describes what the function does.
#     """
#     # Function body (set of instructions)
#     return value   # Optional (can return a result or nothing)

# 3. Specialized Functions
# Syntax:
# lambda arguments: expression
