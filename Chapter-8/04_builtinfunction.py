# Built-in Function:
# Predefined functions that come bundled with Python.

# Example:
# Input/Output Functions:
name = input("Enter your name: ")
print("Hello,", name)

# Type Conversion Functions:
num = "100"
print(int(num) + 50)   # 150

# Mathematical Functions
print(abs(-7))    # 7
print(pow(2, 3))  # 8
print(max(3, 5, 2))  # 5

# Sequence Functions
numbers = [3, 1, 4, 2]
print(len(numbers))      # 4
print(sum(numbers))      # 10
print(sorted(numbers))   # [1, 2, 3, 4]

# Utility Functions
x = "Hello"
print(type(x))    # <class 'str'>
print(id(x))      # Some unique memory address
